#!/usr/bin/env bash
# -----------------------------------------------------------------------------
# setup-ec2.sh - install and start the banking platform on ONE Ubuntu server.
#
# Tested target: AWS EC2, Ubuntu Server 24.04 LTS, t3.medium (4 GB RAM).
# Run it from the repo root, as the normal "ubuntu" user (it uses sudo):
#
#   git clone https://github.com/<you>/banking-platform.git
#   cd banking-platform
#   bash infrastructure/aws/setup-ec2.sh
#
# Safe to run again: it only does what is still missing, then rebuilds and
# restarts the containers. To deploy new code:  git pull && bash infrastructure/aws/setup-ec2.sh
#
# What it does:
#   1. adds a 2 GB swap file (the stack needs ~3.5 GB, swap gives headroom)
#   2. installs Docker Engine + compose/buildx plugins (official script)
#   3. creates docker/.env.prod with random passwords (only the first time)
#   4. builds the images ONE BY ONE (parallel Maven builds would run out of RAM)
#   5. starts everything with docker-compose.prod.yml and waits until healthy
# -----------------------------------------------------------------------------
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
COMPOSE_FILE="${REPO_ROOT}/docker/docker-compose.prod.yml"
ENV_FILE="${REPO_ROOT}/docker/.env.prod"
SWAP_SIZE="${SWAP_SIZE:-2G}"

log() { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }
warn() { printf '\033[1;33mWARN: %s\033[0m\n' "$*"; }

[ -f "${COMPOSE_FILE}" ] || { echo "Run this from inside the banking-platform repo" >&2; exit 1; }

# ---------------------------------------------------------------- 0. checks --
MEM_MB=$(awk '/MemTotal/ {print int($2/1024)}' /proc/meminfo)
if [ "${MEM_MB}" -lt 3500 ]; then
  warn "This server has ${MEM_MB} MB RAM. The stack needs ~3.5 GB; use t3.medium (4 GB) or bigger."
  warn "Continuing anyway with swap, but services may be very slow or get killed."
fi

# ------------------------------------------------------------------ 1. swap --
if ! swapon --show | grep -q .; then
  log "Creating ${SWAP_SIZE} swap file"
  sudo fallocate -l "${SWAP_SIZE}" /swapfile
  sudo chmod 600 /swapfile
  sudo mkswap /swapfile >/dev/null
  sudo swapon /swapfile
  grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' | sudo tee -a /etc/fstab >/dev/null
  # Prefer RAM, use swap only under pressure
  echo 'vm.swappiness=10' | sudo tee /etc/sysctl.d/99-banking-swap.conf >/dev/null
  sudo sysctl -q -p /etc/sysctl.d/99-banking-swap.conf
else
  log "Swap already present - skipping"
fi

# ---------------------------------------------------------------- 2. docker --
if ! command -v docker >/dev/null 2>&1; then
  log "Installing Docker Engine (get.docker.com)"
  curl -fsSL https://get.docker.com -o /tmp/get-docker.sh
  sudo sh /tmp/get-docker.sh
  sudo usermod -aG docker "${USER}" || true
  sudo systemctl enable --now docker
else
  log "Docker already installed: $(docker --version)"
fi
# Use sudo for docker in this run (the group change needs a new login)
DOCKER="sudo docker"
${DOCKER} compose version >/dev/null 2>&1 || { echo "docker compose plugin missing" >&2; exit 1; }

# ------------------------------------------------------------ 3. .env.prod --
if [ ! -f "${ENV_FILE}" ]; then
  log "Creating ${ENV_FILE} with random secrets"
  # Public IP from the EC2 metadata service (IMDSv2); fall back to localhost
  TOKEN=$(curl -fsS -m 2 -X PUT "http://169.254.169.254/latest/api/token" \
          -H "X-aws-ec2-metadata-token-ttl-seconds: 60" 2>/dev/null || true)
  PUBLIC_IP=$(curl -fsS -m 2 -H "X-aws-ec2-metadata-token: ${TOKEN}" \
          http://169.254.169.254/latest/meta-data/public-ipv4 2>/dev/null || echo "localhost")
  umask 077
  cat > "${ENV_FILE}" <<EOF
# Generated by setup-ec2.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep this file secret.
POSTGRES_USER=banking
POSTGRES_PASSWORD=$(openssl rand -hex 24)
JWT_SECRET=$(openssl rand -base64 48 | tr -d '\n')
JWT_EXPIRY=PT1H
PUBLIC_URL=http://${PUBLIC_IP}
HTTP_PORT=80
EOF
  umask 022
else
  log "${ENV_FILE} exists - keeping the existing secrets"
fi

COMPOSE="${DOCKER} compose -f ${COMPOSE_FILE} --env-file ${ENV_FILE}"

# ----------------------------------------------------------------- 4. build --
# One image at a time: each Maven build needs ~1 GB RAM.
export DOCKER_BUILDKIT=1
for svc in account-service transaction-service fraud-service notification-service audit-service api-gateway web postgres; do
  log "Building ${svc}"
  ${COMPOSE} build "${svc}"
done

# ----------------------------------------------------------------- 5. start --
log "Starting the stack"
${COMPOSE} up -d --remove-orphans

log "Waiting for the API gateway to become healthy (first start can take 3-5 minutes)"
for i in $(seq 1 60); do
  status=$(${DOCKER} inspect -f '{{.State.Health.Status}}' banking-api-gateway 2>/dev/null || echo "starting")
  if [ "${status}" = "healthy" ]; then
    break
  fi
  sleep 10
  printf '.'
done
echo

${COMPOSE} ps

if curl -fsS -m 5 -X POST http://localhost/api/v1/auth/login \
     -H 'Content-Type: application/json' \
     -d '{"username":"rahul","password":"password"}' >/dev/null; then
  PUBLIC_URL=$(grep '^PUBLIC_URL=' "${ENV_FILE}" | cut -d= -f2-)
  log "Done! Open ${PUBLIC_URL} in your browser (login: rahul / password, admin / admin123)"
else
  warn "Login check failed. Look at the logs:  sudo docker compose -f docker/docker-compose.prod.yml --env-file docker/.env.prod logs --tail=100"
fi
