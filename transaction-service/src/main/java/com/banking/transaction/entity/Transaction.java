package com.banking.transaction.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EntityListeners;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.ToString;
import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.annotation.LastModifiedDate;
import org.springframework.data.jpa.domain.support.AuditingEntityListener;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.UUID;

/**
 * One deposit, withdrawal or transfer.
 * <p>
 * The id is generated by us (not the DB) so it can be used as the Kafka key / aggregateId
 * before the row is flushed. {@code @Version} gives optimistic locking, so two Kafka events
 * can't update the same transaction at the same time without one of them noticing.
 */
@Entity
@Table(name = "transactions")
@EntityListeners(AuditingEntityListener.class)
@Getter
@Setter
@Builder
@NoArgsConstructor
@AllArgsConstructor
@ToString
public class Transaction {

    @Id
    private UUID id;

    /** Human-friendly unique reference, e.g. TXN20261121AB12CD34. */
    @Column(nullable = false, unique = true, length = 32)
    private String reference;

    @Enumerated(EnumType.STRING)
    @Column(name = "transaction_type", nullable = false, length = 20)
    private TransactionType transactionType;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private TransactionStatus status;

    /** Null for deposits. */
    @Column(name = "source_account_id", length = 64)
    private String sourceAccountId;

    /** Null for withdrawals. */
    @Column(name = "destination_account_id", length = 64)
    private String destinationAccountId;

    @Column(nullable = false, precision = 19, scale = 2)
    private BigDecimal amount;

    @Column(nullable = false, length = 3)
    private String currency;

    @Column(length = 255)
    private String description;

    /** userId of whoever created the transaction. */
    @Column(name = "initiated_by", nullable = false, length = 64)
    private String initiatedBy;

    @Column(name = "idempotency_key", length = 100)
    private String idempotencyKey;

    /** Country from the X-Client-Country header (used by fraud rules). */
    @Column(name = "client_country", length = 8)
    private String clientCountry;

    /** Shared by every Kafka event of this transaction's saga. */
    @Column(name = "correlation_id", nullable = false, length = 64)
    private String correlationId;

    @Column(name = "failure_reason", length = 500)
    private String failureReason;

    /** ErrorCode name, e.g. INSUFFICIENT_FUNDS or FRAUD_BLOCKED. */
    @Column(name = "failure_code", length = 50)
    private String failureCode;

    /** 0-100 score from fraud-service. */
    @Column(name = "risk_score")
    private Integer riskScore;

    @CreatedDate
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @LastModifiedDate
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    @Column(name = "completed_at")
    private Instant completedAt;

    @Version
    private Long version;
}
